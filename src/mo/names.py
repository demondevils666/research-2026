"""Короткие названия МО для текста отчета, подписей рисунков и лендинга (одна функция на все три места)."""

import re

FEDERAL = ("внутригородская территория города федерального значения ",
           "внутригородское муниципальное образование города федерального значения ")
CITY = ("городской округ город-герой ", "городской округ город-курорт ", "городской округ город ")
# «городской округ Талдомский» без слова «округ» читается как город или район: оставляем «г. о.» / «м. о.»
PREFIX = (("городской округ ", " г. о."), ("муниципальный округ ", " м. о."), ("муниципальный район ", " р-н"))
ADJECTIVE = re.compile(r"^[А-ЯЁ][а-яё-]*(ский|цкий|ской)$")


def short(name: str) -> str:
    """«городской округ город Майкоп» -> «Майкоп», «Иркутский муниципальный район» -> «Иркутский р-н»,
    «городской округ Талдомский» -> «Талдомский г. о.»."""
    name = name.replace('""', "").strip()
    for pre in FEDERAL:
        if name.startswith(pre):
            return name[len(pre):].removeprefix("муниципальный округ ")
    for pre in CITY:
        if name.startswith(pre):
            return name[len(pre):]
    for pre, suffix in PREFIX:
        if name.startswith(pre):
            rest = name[len(pre):]
            return rest + suffix if ADJECTIVE.match(rest) else rest
    return name.replace(" муниципальный район", " р-н").replace(" муниципальный округ", " м. о.")
